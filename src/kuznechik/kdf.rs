use streebog::{Digest, Streebog256};
pub struct KdfGost3411_2012_256;

impl KdfGost3411_2012_256 {
    /// Реализация KDF на основе ГОСТ Р 34.11-2012 (256-битная версия)
    /// Возвращает фиксированный массив [u8; 32] (256 бит)
    pub fn derive_256bit(
        key: &[u8],
        label: &[u8],
        seed: &[u8],
    ) -> [u8; 32] {
        // Формируем входные данные по ГОСТу:
        // Формат: 0x01 || K_in || label || seed
        
        let mut input = Vec::new();
        
        // 1. Добавляем счетчик 0x01 (1 байт)
        input.push(0x01);
        
        // 2. Добавляем ключ K_in
        input.extend_from_slice(key);
        
        // 3. Добавляем label (если есть)
        if !label.is_empty() {
            input.extend_from_slice(label);
        }
        
        // 4. Добавляем seed (если есть)
        if !seed.is_empty() {
            input.extend_from_slice(seed);
        }
        
        // 5. Вычисляем хеш ГОСТ Р 34.11-2012 (Streebog-256)
        let mut hasher = Streebog256::new();
        hasher.update(&input);
        let hash = hasher.finalize();
        
        // 6. Конвертируем в массив [u8; 32]
        let mut result = [0u8; 32];
        result.copy_from_slice(&hash);
        
        result
    }
}

